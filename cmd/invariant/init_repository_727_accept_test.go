func initWrite727(t *testing.T, root, name, body string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func initRead727(t *testing.T, root, name string) []byte {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(name)))
	if err != nil {
		t.Fatalf("init did not produce %s: %v", name, err)
	}
	return b
}

func initGuidance727(t *testing.T, printed string) {
	t.Helper()
	lower := strings.ToLower(printed)
	for _, want := range []string{repository.Path, "review", "commit", "base branch", "configured", "gate", "external plumbing", "disabled"} {
		if !strings.Contains(lower, want) {
			t.Errorf("init guidance lacks %q:\n%s", want, printed)
		}
	}
}

func TestInit727DraftsAndExplains(t *testing.T) {
	for _, tc := range []struct {
		name  string
		files map[string]string
		parts int
	}{
		{"Go", map[string]string{"go.mod": "module example.invalid/app\n\ngo 1.27.1\n"}, 1},
		{"Python", map[string]string{"requirements.txt": "pytest>=8\n"}, 1},
		{"TypeScript", map[string]string{"package.json": `{"name":"web","private":true}`}, 1},
		{"mixed", map[string]string{"go.mod": "module example.invalid/app\n\ngo 1.27.1\n", "web/package.json": `{"name":"web","private":true}`}, 2},
		{"no project", map[string]string{"README.md": "A project will be added later.\n"}, 0},
		{"modeled only", map[string]string{
			".invariant/invariant.json": `{"name":"legacy","module":"spec.tla","code":"core","language":"go"}`,
			".invariant/ratified.lock":  `{"bounds":{"N":"2"},"statements":[{"name":"Spec","kind":"spec","says":"The behaviors"},{"name":"Safe","kind":"invariant","says":"Safe states"}]}`,
			"spec.tla":                  "---- MODULE Fixture ----\n====\n", "core/core.go": "package core\n",
		}, 0},
	} {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			for name, body := range tc.files {
				initWrite727(t, root, name, body)
			}
			var before *project.Project
			if tc.name == "modeled only" {
				var err error
				before, err = project.Load(root)
				if err != nil {
					t.Fatal(err)
				}
			}
			code, printed := initPrints(t, "-repo", "acme/widgets", "-invariant", initPin, root)
			if code != 0 {
				t.Fatalf("drafting setup exited %d:\n%s", code, printed)
			}
			b := initRead727(t, root, repository.Path)
			var c struct {
				Parts      []repository.Part `json:"parts"`
				Unresolved []string          `json:"unresolved"`
			}
			if err := json.Unmarshal(b, &c); err != nil {
				t.Fatalf("invalid draft JSON: %v\n%s", err, b)
			}
			if len(c.Parts) != tc.parts || len(c.Unresolved) == 0 {
				t.Errorf("want %d parts and explicit unresolved items, got %s", tc.parts, b)
			}
			if !strings.Contains(strings.ToLower(printed), "unresolved") {
				t.Errorf("init hides incomplete checks:\n%s", printed)
			}
			initGuidance727(t, printed)
			want, err := setup.Workflow(initPin)
			if err != nil {
				t.Fatal(err)
			}
			if got := initRead727(t, root, setup.WorkflowPath); string(got) != want {
				t.Errorf("drafting changed the pinned modeled gate:\n%s", got)
			}
			for _, kept := range []string{"invariant watch -repo acme/widgets", "invariant/gate", "allow_merge_commit=true", "docs/factory-app.md"} {
				if !strings.Contains(printed, kept) {
					t.Errorf("modeled setup lost %q:\n%s", kept, printed)
				}
			}
			if before != nil {
				after, err := project.Load(root)
				if err != nil {
					t.Fatal(err)
				}
				if !reflect.DeepEqual(before.Manifest, after.Manifest) || !reflect.DeepEqual(before.Lock, after.Lock) {
					t.Fatal("repository drafting changed modeled-project loading")
				}
				for name, body := range tc.files {
					if got := initRead727(t, root, name); string(got) != body {
						t.Errorf("changed existing modeled file %s", name)
					}
				}
			}
		})
	}
}

func TestInit727KeepsExistingConfiguration(t *testing.T) {
	root := t.TempDir()
	initWrite727(t, root, "go.mod", "module example.invalid/app\n\ngo 1.27.1\n")
	args := []string{"-repo", "acme/widgets", "-invariant", initPin, root}
	if code, printed := initPrints(t, args...); code != 0 {
		t.Fatalf("first init: %d\n%s", code, printed)
	}
	first := initRead727(t, root, repository.Path)
	if code, printed := initPrints(t, args...); code != 0 {
		t.Fatalf("repeat init: %d\n%s", code, printed)
	}
	if !bytes.Equal(first, initRead727(t, root, repository.Path)) {
		t.Fatal("repeat init changed generated bytes")
	}
	// Preservation does not depend on parsing or endorsing the person's file.
	custom := "{\"version\":1,\"custom\":\"Keep these exact bytes until I finish reviewing.\"}\n"
	initWrite727(t, root, repository.Path, custom)
	for _, force := range []bool{false, true} {
		args := []string{"-repo", "acme/widgets", "-invariant", initPin}
		if force {
			initWrite727(t, root, setup.WorkflowPath, "name: customized workflow\n")
			args = append(args, "-force")
		}
		args = append(args, root)
		code, printed := initPrints(t, args...)
		if code != 0 {
			t.Fatalf("preserving configuration (force=%v): %d\n%s", force, code, printed)
		}
		if got := initRead727(t, root, repository.Path); string(got) != custom {
			t.Fatalf("force=%v overwrote customized configuration: %s", force, got)
		}
		lower := strings.ToLower(printed)
		if !strings.Contains(lower, repository.Path) || !(strings.Contains(lower, "kept") || strings.Contains(lower, "preserv")) || !strings.Contains(lower, "existing") {
			t.Errorf("preservation was not clearly reported:\n%s", printed)
		}
		initGuidance727(t, printed)
		want, _ := setup.Workflow(initPin)
		if got := initRead727(t, root, setup.WorkflowPath); string(got) != want {
			t.Error("-force no longer replaces a customized workflow")
		}
	}
}

func TestInit727ConfinesWritesAndRequiresPin(t *testing.T) {
	for _, linkedParent := range []bool{true, false} {
		t.Run(map[bool]string{true: "linked directory", false: "linked file"}[linkedParent], func(t *testing.T) {
			root, outside := t.TempDir(), t.TempDir()
			initWrite727(t, root, "go.mod", "module example.invalid/app\n\ngo 1.27.1\n")
			initWrite727(t, outside, "repository.json", "outside sentinel\n")
			if linkedParent {
				if err := os.Symlink(outside, filepath.Join(root, ".invariant")); err != nil {
					t.Fatal(err)
				}
			} else {
				if err := os.MkdirAll(filepath.Join(root, ".invariant"), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(filepath.Join(outside, "repository.json"), filepath.Join(root, repository.Path)); err != nil {
					t.Fatal(err)
				}
			}
			code, printed := initPrints(t, "-repo", "acme/widgets", "-invariant", initPin, root)
			if code == 0 {
				t.Fatalf("init accepted a linked configuration destination:\n%s", printed)
			}
			if !strings.Contains(printed, ".invariant") {
				t.Errorf("unsafe destination not identified:\n%s", printed)
			}
			if got := initRead727(t, outside, "repository.json"); string(got) != "outside sentinel\n" {
				t.Fatal("init wrote through a symlink")
			}
			entries, err := os.ReadDir(outside)
			if err != nil || len(entries) != 1 {
				t.Fatalf("init changed outside directory: %v, %v", entries, err)
			}
		})
	}
	for _, pin := range []string{"", "main", "61eb049"} {
		t.Run("invalid pin "+pin, func(t *testing.T) {
			root := t.TempDir()
			initWrite727(t, root, "go.mod", "module example.invalid/app\n\ngo 1.27.1\n")
			code, printed := initPrints(t, "-repo", "acme/widgets", "-invariant", pin, root)
			if code == 0 {
				t.Fatalf("init accepted invalid pin %q:\n%s", pin, printed)
			}
			for _, name := range []string{repository.Path, setup.WorkflowPath} {
				if _, err := os.Lstat(filepath.Join(root, name)); !os.IsNotExist(err) {
					t.Errorf("init wrote %s with invalid pin: %v", name, err)
				}
			}
		})
	}
}
