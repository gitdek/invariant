package plumbing

import (
	"strings"
	"testing"
)

// Admission and pip must read a requirements lockfile the same way. If a line
// admission takes for a comment reaches pip as an option, --no-binary=:all:
// can build a source package, whose build code runs during the networked
// install, and --index-url can redirect it (#748).
func TestDependencyPythonLockReadsAsPipDoes(t *testing.T) {
	hash := "--hash=sha256:" + strings.Repeat("c", 64)
	for _, tc := range []struct {
		name, lock string
		admitted   bool
	}{
		{"pip-compile output", "#\n# This file is autogenerated by pip-compile with Python 3.13\n#    pip-compile --generate-hashes requirements.in\n#\npackaging==24.2 \\\n    " + hash + " \\\n    --hash=sha256:" + strings.Repeat("d", 64) + "\n    # via -r requirements.in\n", true},
		{"CRLF line endings", "packaging==24.2 \\\r\n    " + hash + "\r\n", true},
		{"inline comment after whitespace", "packaging==24.2 " + hash + "\t# pinned\n", true},
		{"bare carriage return", "packaging==24.2 " + hash + " #\r--no-binary=:all:\n", false},
		{"comment continued onto an option", "packaging==24.2 " + hash + "\n# note \\\n--no-binary=:all:\n", false},
		{"indented comment continued", "packaging==24.2 " + hash + "\n    # via \\\n--index-url https://example.invalid/simple\n", false},
		{"coding declaration", "# -*- coding: utf-7 -*-\npackaging==24.2 " + hash + " #+AAo---no-binary=:all:\n", false},
		{"comment without whitespace", "packaging==24.2 " + hash + "#--no-binary=:all:\n", false},
		{"form feed", "packaging==24.2 " + hash + " #\f--no-binary=:all:\n", false},
		{"Unicode line separator", "packaging==24.2 " + hash + " #\u2028--no-binary=:all:\n", false},
		{"byte-order mark", "\ufeffpackaging==24.2 " + hash + "\n", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := dependencyInstall(part468("python", "."), map[string][]byte{"requirements.lock": []byte(tc.lock)})
			if tc.admitted && err != nil {
				t.Fatalf("admission refused a lockfile pip reads as it does: %v", err)
			}
			if !tc.admitted && err == nil {
				t.Fatalf("admission accepted a lockfile pip reads differently:\n%q", tc.lock)
			}
		})
	}
}
